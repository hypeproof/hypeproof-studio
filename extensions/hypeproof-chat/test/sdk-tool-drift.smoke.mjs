// SDK tool-drift guard (#375). Studio's tool surface is a hand-maintained
// allowlist (SDK_READ/WRITE/AGENT_TOOL_NAMES, SEARCH_TOOLS, Bash, MCP browser
// tools). Deny-by-default is the right design, but it only stays current if
// someone notices when the Agent SDK moves: bump @anthropic-ai/claude-agent-sdk,
// a new tool ships, and the model quietly can't use it — denied exactly like a
// routine policy denial, in a console nobody reads.
//
// This test turns that silent drift into a green/red signal at PR time. It
// enumerates the INSTALLED SDK's actual tool surface (the ToolInputSchemas
// union in sdk-tools.d.ts — generated by json-schema-to-typescript, so it is
// canonical and enumerable at test time) and asserts every tool is either
// CLASSIFIED by the policy matrix (isClassifiedSdkToolName — which includes the
// SDK_DENIED_TOOLS table in sdkCoachHelpers.ts, each entry with its reason) or
// explicitly listed in ACKNOWLEDGED_UNSUPPORTED below — the record of older
// tools we have looked at and consciously chosen not to wire. A genuinely NEW
// SDK tool is neither, so it fails here and forces a look instead of shipping
// as silence.
//
// 0.3.299 (A2): the union went from 40 to 44 names. Added: OfferChromeSetup,
// ProposeGoal, ProposeSkills, ReadNotifications, RefreshMcpTools, SendFeedback.
// Removed: REPL, TaskOutput. Changed inputs: Agent (+effort), Read
// (+allow_large), WebFetch (+offset) — all three stay classified as before —
// and Artifact, Projects, RemoteTrigger, ScheduleWakeup, Monitor,
// ReportFindings, which moved from the acknowledged list here into
// SDK_DENIED_TOOLS with a stated reason. PowerShell is a runtime-only built-in
// (no typings entry) and is classified under the shell gate.
//
// Run: node --experimental-strip-types test/sdk-tool-drift.smoke.mjs

import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));

const { isClassifiedSdkToolName, evaluateSdkToolUse, SDK_DENIED_TOOLS, sdkDeniedToolReason } = await import(
  "../src/sdkCoachHelpers.ts"
);

// ─── the drift flag on evaluateSdkToolUse denials (#375, unit) ───────────────
// The mechanical half of the fix: the not-granted gate flags a name the matrix
// has never classified as `drift`, distinct from a routine profile denial.
{
  const adultRW = ["Read", "Grep", "Glob", "Write", "Edit", "MultiEdit"];

  // Classified names denied by policy are NOT drift (expected, high-volume).
  for (const name of ["Bash", "WebFetch", "Read", "Write", "Edit", "Agent"]) {
    assert.ok(isClassifiedSdkToolName(name), `${name} must be a classified tool name`);
  }
  const bash = evaluateSdkToolUse({ toolName: "Bash", input: { command: "ls" }, permittedTools: adultRW });
  assert.ok(bash.decision === "deny" && !bash.drift, "Bash denial is routine policy, not drift");

  // A name the matrix has never heard of IS drift, and stays a fail-closed deny.
  for (const unknown of ["MysteryTool", "mcp__github__create_pr", "ComputerUse", "Websearch2"]) {
    assert.ok(!isClassifiedSdkToolName(unknown), `${unknown} must be unclassified`);
    const v = evaluateSdkToolUse({ toolName: unknown, input: {}, permittedTools: adultRW });
    assert.equal(v.decision, "deny", `${unknown} still fails closed`);
    assert.equal(v.drift, true, `${unknown} is flagged as SDK tool drift`);
  }
}

// ─── the installed SDK's tool surface is fully accounted for (#375, CI) ──────
// Locate the installed SDK type definitions. The extension keeps the SDK as a
// devDependency (never prod — see sdk-gateway.smoke.mjs); `npm test` installs
// it, so this file is present when the suite runs.
const dtsPath = join(here, "..", "node_modules", "@anthropic-ai", "claude-agent-sdk", "sdk-tools.d.ts");
let dts;
try {
  dts = readFileSync(dtsPath, "utf8");
} catch {
  assert.fail(
    `Cannot read the installed Agent SDK tool schema at ${dtsPath}. ` +
      `Run \`npm install\` in extensions/hypeproof-chat before the smoke suite so drift can be checked against the real SDK.`,
  );
}

// json-schema-to-typescript names the file tools FileRead/FileWrite/FileEdit;
// the SDK emits them at runtime as Read/Write/Edit (verified against sdk.mjs).
const TYPE_TO_TOOL_NAME = { FileRead: "Read", FileWrite: "Write", FileEdit: "Edit" };

/**
 * The canonical tool surface: the `export type ToolInputSchemas = A | B | …;`
 * union. Each member is a `<TypeName>Input` interface; the runtime tool name is
 * the type name minus the "Input" suffix, with the File* names aliased.
 */
function runtimeToolNames(text) {
  const unionMatch = text.match(/export type ToolInputSchemas\s*=([\s\S]*?);/);
  assert.ok(unionMatch, "sdk-tools.d.ts must declare the ToolInputSchemas union");
  const inputTypeNames = [...unionMatch[1].matchAll(/([A-Za-z0-9_]+)Input\b/g)].map((m) => m[1]);
  // ToolOutputSchemas is referenced from the union tail but is not a tool input.
  return [...new Set(inputTypeNames)]
    .filter((n) => n !== "ToolOutputSchemas")
    .map((n) => TYPE_TO_TOOL_NAME[n] ?? n);
}

// Tools that exist in the SDK but Studio's chat-first coach deliberately does
// NOT classify/grant, and that 0.3.299 left unchanged. This list is the "we
// looked and chose not to wire it" record: adding a name here is a conscious
// decision, and a NEW SDK tool that is neither classified nor listed here
// fails the assertion below — which is the point. Tools whose denial needs a
// stated product reason live in SDK_DENIED_TOOLS instead (one place per name).
const ACKNOWLEDGED_UNSUPPORTED = new Set([
  "AskUserQuestion",
  "ClaudeDesign",
  "CronCreate",
  "CronDelete",
  "CronList",
  "EnterPlanMode",
  "EnterWorktree",
  "ExitPlanMode",
  "ExitWorktree",
  "ListMcpResources",
  "Mcp",
  "PushNotification",
  "ReadMcpResource",
  "ReadMcpResourceDir",
  "ShowOnboardingRolePicker",
  "TaskCreate",
  "TaskGet",
  "TaskList",
  "TaskStop",
  "TaskUpdate",
  "TodoWrite",
  "Workflow",
]);

/** Account for a tool surface: what the matrix wires, what it denies by name, what nobody decided. */
function accountFor(names, acknowledged = ACKNOWLEDGED_UNSUPPORTED) {
  const unaccounted = [];
  let wired = 0;
  for (const name of names) {
    if (isClassifiedSdkToolName(name)) {
      if (sdkDeniedToolReason(name) === undefined) wired += 1;
      continue;
    }
    if (acknowledged.has(name)) continue;
    unaccounted.push(name);
  }
  const present = new Set(names);
  const stale = [...acknowledged, ...Object.keys(SDK_DENIED_TOOLS)].filter((n) => !present.has(n));
  return { unaccounted, wired, stale };
}

const installed = runtimeToolNames(dts);
assert.ok(installed.length >= 30, `expected a substantial SDK tool surface, got ${installed.length}`);

// ─── positive control: the real installed surface is fully decided ──────────
{
  const { unaccounted, wired, stale } = accountFor(installed);
  assert.deepEqual(
    unaccounted,
    [],
    `\nSDK TOOL DRIFT: the installed @anthropic-ai/claude-agent-sdk exposes tool(s) the policy matrix neither ` +
      `classifies nor deliberately excludes:\n  ${unaccounted.join(", ")}\n` +
      `If Studio should handle a tool, wire it into SDK_*_TOOL_NAMES / the *_TOOLS sets in sdkCoachHelpers.ts. ` +
      `If it must stay away from learners, add it to SDK_DENIED_TOOLS there with the reason; if it is merely ` +
      `unused, add it to ACKNOWLEDGED_UNSUPPORTED in this test. Either way, make the choice on purpose.`,
  );
  // Sanity: the wired count matches the built-in surface we grant today
  // (Read, Write, Edit, Grep, Glob, NotebookEdit, WebFetch, WebSearch, Agent,
  // Bash). If this drops, a tool we DO classify vanished from the SDK.
  assert.ok(wired >= 8, `expected the SDK to still expose the built-in tools Studio classifies; only ${wired} matched`);
  // Stale entries: a decision about a name the installed SDK no longer has
  // reads as coverage it is not (REPL and TaskOutput left in 0.3.299).
  assert.deepEqual(stale, [], `decided tool names missing from the installed SDK (remove them): ${stale.join(", ")}`);
}

// ─── negative controls: the check still fails on what it must catch ─────────
// Without these, a parser that silently returned [] would keep the test green
// forever (verification rule 2: the bad sample must fail).
{
  // A future SDK tool nobody has decided on: planted into a copy of the real union.
  const planted = dts.replace(/export type ToolInputSchemas\s*=/, "export type ToolInputSchemas = QuantumLeapInput |");
  assert.notEqual(planted, dts, "control setup: the union was found and planted");
  const plantedNames = runtimeToolNames(planted);
  assert.ok(plantedNames.includes("QuantumLeap"), "control setup: the planted name parses");
  assert.deepEqual(accountFor(plantedNames).unaccounted, ["QuantumLeap"], "an undecided new tool must be reported");

  // A decision about a tool that is not there.
  const withGhost = new Set([...ACKNOWLEDGED_UNSUPPORTED, "LongGoneTool"]);
  assert.deepEqual(accountFor(installed, withGhost).stale, ["LongGoneTool"], "a stale acknowledgement must be reported");

  // Removing a decision makes that tool undecided again: the acknowledged list carries weight.
  const withoutTodo = new Set([...ACKNOWLEDGED_UNSUPPORTED].filter((n) => n !== "TodoWrite"));
  assert.deepEqual(accountFor(installed, withoutTodo).unaccounted, ["TodoWrite"], "dropping an acknowledgement reopens it");
}

// ─── one decision per name ───────────────────────────────────────────────────
{
  const both = Object.keys(SDK_DENIED_TOOLS).filter((n) => ACKNOWLEDGED_UNSUPPORTED.has(n));
  assert.deepEqual(both, [], "a name is either denied with a reason in code or acknowledged here, never both");
  for (const [name, reason] of Object.entries(SDK_DENIED_TOOLS)) {
    assert.ok(typeof reason === "string" && reason.length >= 30, `${name}: the denial states a real reason`);
  }
}

// ─── 0.3.299 additions and changes: denied by name, routinely, for everyone ──
// SendFeedback, ReadNotifications, RefreshMcpTools and OfferChromeSetup must
// never run for learners (ProposeGoal and ProposeSkills too). The deny holds
// even when a polluted permitted set lists the name — and it is NOT drift: the
// matrix decided it.
{
  const ADDED_0_3_299 = ["OfferChromeSetup", "ProposeGoal", "ProposeSkills", "ReadNotifications", "RefreshMcpTools", "SendFeedback"];
  const CHANGED_NEVER_GRANTED = ["Artifact", "Projects", "RemoteTrigger", "ScheduleWakeup", "Monitor", "ReportFindings"];
  for (const name of [...ADDED_0_3_299, ...CHANGED_NEVER_GRANTED]) {
    assert.ok(installed.includes(name), `${name} is in the installed 0.3.299 surface`);
    assert.ok(isClassifiedSdkToolName(name), `${name} is classified in code, not only acknowledged in a test`);
    assert.ok(!ACKNOWLEDGED_UNSUPPORTED.has(name), `${name} is decided in SDK_DENIED_TOOLS`);
    for (const permittedTools of [[], ["Read", "Write"], [name], ["Read", name, "Bash"]]) {
      const v = evaluateSdkToolUse({ toolName: name, input: {}, permittedTools, workspaceRoot: "/ws" });
      assert.equal(v.decision, "deny", `${name} is denied with permittedTools=${JSON.stringify(permittedTools)}`);
      assert.ok(!v.drift, `${name} denial is a decided policy, not drift`);
      assert.match(v.reason, /never available to learners/, `${name}: the logged reason says why`);
      assert.ok(v.friendly.length > 0, `${name}: the learner sees the Korean line`);
    }
  }
  // Positive control: Gate 0 is a name list, not a blanket — a granted read still runs.
  assert.deepEqual(
    evaluateSdkToolUse({ toolName: "Read", input: { file_path: "/ws/index.html" }, permittedTools: ["Read"], workspaceRoot: "/ws" }),
    { decision: "allow" },
    "a granted, contained Read is still allowed",
  );
  // Names are exact, as the SDK emits them: a near miss is not on the list.
  assert.equal(sdkDeniedToolReason("sendfeedback"), undefined, "the deny table matches exact runtime names");
  assert.equal(sdkDeniedToolReason("toString"), undefined, "prototype members are not entries");
}

// ─── runtime-only built-ins: in the CLI, absent from the typings ─────────────
// PowerShell is the shell tool the 2.1.299 CLI registers on Windows when Git
// Bash is missing (binary: `vw()` enables it there by default). The union above
// cannot see it, so it is listed and checked here.
{
  const RUNTIME_ONLY_BUILTINS = ["PowerShell"];
  for (const name of RUNTIME_ONLY_BUILTINS) {
    assert.ok(!installed.includes(name), `${name} has no typings entry (if it gains one, the union check covers it)`);
    assert.ok(isClassifiedSdkToolName(name), `${name} is classified (under the shell gate)`);
  }
  // Negative control: classification is by the tool's real name only.
  for (const lookalike of ["Pwsh", "PowerShellX", "PowerShell7"]) {
    assert.ok(!isClassifiedSdkToolName(lookalike), `${lookalike} is not a tool name the matrix knows`);
  }
}

console.log("✓ #375: SDK tool drift — denials flagged apart + installed 0.3.299 surface fully decided (with controls)");
