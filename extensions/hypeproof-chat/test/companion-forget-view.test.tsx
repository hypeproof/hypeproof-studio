// Actual React/ReactDOM events in the existing mini DOM; no storage/host authority is fabricated.
import { mountPoint, click } from './fixtures/mini-dom.mjs';
import React from 'react';
import { createRoot } from 'react-dom/client';
import assert from 'node:assert/strict';
import { CompanionSessionView } from '../webview-ui/src/CompanionSessionView';
import type { CompanionSessionSnapshot, CompanionSessionController } from '../webview-ui/src/companionSessionPresentation';
import type { CompanionHostRequest } from '../src/companionHostDispatch';
const reactAct = (React as unknown as { act(fn: () => unknown): Promise<void> }).act;
const act = (fn: () => unknown) => reactAct(async () => { await fn(); await Promise.resolve(); });
const deferred = () => { let resolve!: () => void; const promise = new Promise<void>(yes => { resolve = yes; }); return { promise, resolve }; };
const request: CompanionHostRequest = { schema:'hps-companion-host-request/1',requestId:'request-1',actorId:'actor',deviceId:'device',hostId:'host',workspaceId:'workspace',projectId:'project',taskId:'task',version:1,epoch:1,consentRevision:1,artifactId:'quiz',artifactVersion:'a'.repeat(64),operation:'preview.read' };
const good: CompanionSessionSnapshot = { computerName:'내 컴퓨터',connection:'connected',selection:{request,projectName:'내 작품',artifactName:'내 퀴즈'},receipt:{request,outcome:{state:'completed',code:'preview_read',requestId:request.requestId,artifact:{id:'quiz',version:request.artifactVersion,text:'exact saved preview'}}},busy:false };
type El = { getAttribute(name:string):string|null; textContent:string; localName:string; findAll(fn:(el:El)=>boolean):El[] };
const host = mountPoint() as unknown as El, root = createRoot(host as unknown as HTMLElement);
let checks = 0, requested = 0, reconnected = 0, forgotten = 0;
const eq = (actual: unknown, expected: unknown, label:string) => { assert.deepEqual(actual, expected, label); checks++; };
const controller: CompanionSessionController = { async requestPreview(){ requested++; }, async reconnect(){ reconnected++; } };
const render = (snapshot:CompanionSessionSnapshot, owner=controller) => act(() => { root.render(<CompanionSessionView snapshot={snapshot} controller={owner} renderPreview={artifact=><div data-testid="rendered-artifact">{artifact.text}</div>}/>); });
const buttons = () => host.findAll(el=>el.localName==='button');
const button = (label:string) => { const found=buttons().find(el=>el.textContent===label); assert.ok(found, 'button '+label); return found; };
const preview = () => host.findAll(el=>el.getAttribute('data-testid')==='rendered-artifact').length;
const state = () => host.findAll(el=>el.getAttribute('data-state')!==null)[0].getAttribute('data-state');
const clearLabel = '이 기기의 보기 기록 지우기';

async function run(){
  await render(good);
  eq(buttons().some(el=>el.textContent===clearLabel),false,'no cleanup action without an explicit callback');
  eq(preview(),1,'existing completed preview remains'); eq(forgotten,0,'mount never deletes');
  const wait = deferred();
  const owner:CompanionSessionController = {...controller, async forget(){forgotten++;await wait.promise;} };
  await render(good,owner); eq(forgotten,0,'opt-in mount also never deletes');
  await act(()=>click(button(clearLabel)));
  const group=host.findAll(el=>el.getAttribute('role')==='group')[0];
  eq(!!group,true,'inline confirmation uses an accessible group');
  eq(host.findAll(el=>el.getAttribute('id')===group.getAttribute('aria-labelledby'))[0].textContent,'이 기기의 보기 기록을 지울까요?','confirmation has a visible accessible name');
  eq(host.findAll(el=>el.getAttribute('id')===group.getAttribute('aria-describedby'))[0].textContent,'컴퓨터의 원본은 그대로 남아요. 이미 허용한 컴퓨터 작업은 되돌리지 않아요.','confirmation names exact local scope and approved-work boundary');
  eq(document.activeElement,button('계속 보기'),'confirmation focuses the nondestructive choice');
  await act(()=>click(button('계속 보기')));
  eq(forgotten,0,'continuing view calls no deletion'); eq(preview(),1,'cancel preserves preview');
  eq(document.activeElement,button(clearLabel),'cancel restores entry focus');
  await act(()=>click(button(clearLabel)));
  await act(()=>{click(button(clearLabel));click(button(clearLabel));click(button('연결 상태 확인'));});
  eq(forgotten,1,'rapid confirm starts exactly one async cleanup');
  eq(buttons().every(el=>el.getAttribute('disabled')!==null),true,'all actions stay disabled while cleanup is pending');
  eq(preview(),1,'promise pending does not hide a still-current preview'); eq(state(),'completed','pending is not falsely cleared');
  eq(host.textContent.includes('이 기기의 보기 기록을 지웠어요'),false,'no success claim before callback completion');
  await act(()=>wait.resolve());
  eq(preview(),0,'awaited success unmounts the preview'); eq(state(),'local_cleared','awaited success shows cleared state');
  eq(host.textContent.includes('내 퀴즈') || host.textContent.includes('내 작품') || host.textContent.includes('연결됨'),false,'cleared view also removes stale artifact titles and active connection claim');
  eq(host.textContent.includes('이미 허용한 컴퓨터 작업은 되돌리지 않았어요.'),true,'success claims no computer undo');
  eq(document.activeElement?.getAttribute('role'),'status','completion focuses the live status');
  eq(buttons().length,0,'cleared view cannot accidentally send/reconnect through its old owner');
  await render({...good},owner); eq(preview(),0,'stale caller receipt cannot resurrect the just-cleared preview');
  await render({...good,selection:{...good.selection!,request:{...request,epoch:2}}},owner);
  eq(state(),'local_cleared','selection updates cannot reopen a terminally cleared owner');
  let fail=true; const retry=deferred();
  const failing:CompanionSessionController={...controller,async forget(){forgotten++;if(fail)throw Error('private token/provider detail');await retry.promise;}};
  await render(good,failing); await act(()=>click(button(clearLabel))); await act(()=>click(button(clearLabel)));
  eq(preview(),1,'failed cleanup does not claim the preview was erased'); eq(state(),'completed','failure never becomes cleared');
  eq(host.findAll(el=>el.getAttribute('role')==='alert')[0].textContent,'보기 기록을 지웠는지 확인하지 못했어요. 다시 시도해 주세요.','failure gives an honest retry message');
  eq(host.textContent.includes('private token'),false,'failure omits raw details');
  fail=false; await act(()=>{click(button('다시 지우기'));click(button('다시 지우기'));}); eq(forgotten,3,'safe retry also guards rapid duplicate gestures');
  // The cleanup owner may drop its current selection before its final erase promise settles.
  await render({...good,selection:null,receipt:null},failing);
  eq(state(),'no_selection','owner clearing selection alone does not claim final deletion');
  await act(()=>retry.resolve()); eq(state(),'local_cleared','same owner confirms completion after its selection is cleared');
  const reconnectWait=deferred();
  const checking:CompanionSessionController={...controller,async reconnect(){reconnected++;await reconnectWait.promise;},async forget(){forgotten++;}};
  await render(good,checking); await act(()=>click(button('연결 상태 확인')));
  await act(()=>click(button(clearLabel))); eq(forgotten,3,'pending status check cannot start cleanup');
  await act(()=>reconnectWait.resolve());
  await render({...good,busy:true},checking); eq(button(clearLabel).getAttribute('disabled')!==null,true,'caller busy state also disables cleanup');
  eq(requested,0,'cleanup interactions never send a preview request'); eq(reconnected,1,'only the explicit connection control reconciles');
  await act(()=>root.unmount());
  console.log(`PASS ${checks} companion local-forget React render assertions; callback contract only. Real storage/transport deletion and browser/device layout NOT_RUN.`);
}
run().then(()=>process.exit(0)).catch(error=>{console.error(error);process.exit(1);});
