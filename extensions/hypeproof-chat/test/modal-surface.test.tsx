import {click,document as doc,mountPoint} from './fixtures/mini-dom.mjs';
import assert from 'node:assert/strict';
import React from 'react';
import {createRoot} from 'react-dom/client';
import {ChatPreferences} from '../webview-ui/src/ChatPreferences';
import {WriteApprovalDialog} from '../webview-ui/src/WriteApprovalDialog';
import {OutboundDialog} from '../webview-ui/src/OutboundDialog';
import {CompletionGate} from '../webview-ui/src/CompletionGate';
for(const name of ['Node','Element','HTMLElement']) (globalThis as any)[name]??=(globalThis.window as any).Element;
const act=(React as any).act, host:any=mountPoint(),root=createRoot(host);
const opener:any=doc.createElement('button');opener.textContent='설정 열기';doc.body.appendChild(opener);
const frame=()=>new Promise(r=>setTimeout(r,25));
const fire=(el:any,key:string,shiftKey=false)=>{const e:any={type:'keydown',key,shiftKey,bubbles:true,cancelable:true,defaultPrevented:false,preventDefault(){this.defaultPrevented=true},stopPropagation(){this._stopped=true}};el.dispatchEvent(e);return e;};
async function main(){
 let close=0,finishAnimation!:()=>void;
 const render=(open:boolean)=>root.render(<ChatPreferences open={open} onClose={()=>{close++;render(false);}}><button>설정 항목</button></ChatPreferences>);
 await act(async()=>render(false));opener.focus();await act(async()=>render(true));
 let dialog:any=host.querySelector('dialog');assert.ok(dialog.getAttribute('class').split(' ').includes('hp-modal'));
 const buttons=dialog.querySelectorAll('button');
 await act(async()=>{buttons.at(-1).focus();fire(buttons.at(-1),'Tab');});assert.ok(doc.activeElement===buttons[0],'Tab wraps');
 await act(async()=>fire(buttons[0],'Tab',true));assert.ok(doc.activeElement===buttons.at(-1),'Shift Tab wraps');
 const pendingExit=new Promise<void>(r=>finishAnimation=r);
 let animationQueries=0;dialog.getAnimations=()=>{animationQueries++;return [{finished:pendingExit}];};
 await act(async()=>fire(buttons.at(-1),'Escape'));
 assert.equal(close,0,'exit retains dialog');assert.equal(dialog.getAttribute('data-closing'),'');assert.ok(dialog.contains(doc.activeElement),'exit retains focus');
 await act(async()=>click(buttons[0]));assert.equal(close,0,'second close cannot bypass exit');assert.equal(animationQueries,1,'duplicate close never starts another exit');
 await act(async()=>{finishAnimation();await Promise.resolve();});await act(frame);
 assert.equal(close,1);assert.ok(doc.activeElement===opener,'focus returns after exit');
 // Reopening clears closing state; with no animation (reduced motion) completion is immediate.
 await act(async()=>render(true));dialog.getAnimations=()=>[];
 await act(async()=>click(dialog.querySelector('button')));assert.equal(close,2);
 // A host close/reopen invalidates the old completion even if the DOM node is reused.
 await act(async()=>render(true));
 let oldExit!:()=>void,newExit!:()=>void;
 const oldPromise=new Promise<void>(r=>oldExit=r);
 dialog.getAnimations=()=>[{finished:oldPromise}];
 await act(async()=>click(dialog.querySelector('button')));
 await act(async()=>render(false));await act(async()=>render(true));
 const newPromise=new Promise<void>(r=>newExit=r);dialog.getAnimations=()=>[{finished:newPromise}];
 await act(async()=>click(dialog.querySelector('button')));
 await act(async()=>{oldExit();await Promise.resolve();});assert.equal(close,2,'old exit cannot close reopened dialog');
 await act(async()=>{newExit();await Promise.resolve();});assert.equal(close,3);
 await act(async()=>render(true));
 let abandoned!:()=>void;const abandonedPromise=new Promise<void>(r=>abandoned=r);
 dialog.getAnimations=()=>[{finished:abandonedPromise}];await act(async()=>click(dialog.querySelector('button')));
 await act(async()=>render(false));await act(async()=>{abandoned();await Promise.resolve();});
 assert.equal(close,3,'external close invalidates pending callback on mounted dialog');
 let answers:any[]=[];
 const prompt={id:'old',title:'저장할까요?',verb:'저장',files:['a.txt']};
 await act(async()=>root.render(<WriteApprovalDialog prompt={prompt} onAnswer={(...v)=>answers.push(v)}/>));
 dialog=host.querySelector('dialog');assert.ok(dialog.getAttribute('class').split(' ').includes('hp-modal'));
 const deny=dialog.querySelector('[data-write-deny]');assert.ok(doc.activeElement===deny,'deny focused');
 let settle!:()=>void;dialog.getAnimations=()=>[{finished:new Promise<void>(r=>settle=r)}];
 const approve=dialog.querySelector('.hps-write-actions').querySelectorAll('button')[1];
 await act(async()=>{click(approve);click(deny);});assert.equal(answers.length,0);
 await act(async()=>{settle();await Promise.resolve();});assert.deepEqual(answers,[['old',true]],'one frozen answer after exit');
 await act(async()=>root.render(<WriteApprovalDialog key="next" prompt={prompt} onAnswer={(...v)=>answers.push(v)}/>));
 dialog=host.querySelector('dialog');dialog.getAnimations=()=>[{finished:new Promise<void>(r=>settle=r)}];
 await act(async()=>click(dialog.querySelector('[data-write-deny]')));
 await act(async()=>root.render(<div>새 활동</div>));
 await act(async()=>{settle();await Promise.resolve();});assert.equal(answers.length,1,'unmount cancels stale answer');
 const outbound:any={id:'out',sections:[{recipient:'강사',items:[{id:'i',label:'질문',bytes:3}]}],excluded:'포함하지 않는 것: 개인 메모',notes:[],public:false};
 await act(async()=>root.render(<OutboundDialog prompt={outbound} onAnswer={(...v)=>answers.push(v)}/>));
 dialog=host.querySelector('dialog');assert.ok(dialog.getAttribute('class').split(' ').includes('hp-modal'));
 dialog.getAnimations=()=>[{finished:new Promise<void>(r=>settle=r)}];
 await act(async()=>click(dialog.querySelector('[data-outbound-cancel]')));assert.equal(answers.length,1);
 await act(async()=>{settle();await Promise.resolve();});assert.deepEqual(answers.at(-1),['out',null]);
 let submitted=0;
 await act(async()=>root.render(<CompletionGate learning={{phase:'working',complete:{ok:true,reasons:[]},declared:true} as any} onSubmit={()=>submitted++}/>));
 await act(async()=>click(host.querySelector('button')));assert.equal(submitted,1);assert.equal(host.querySelector('dialog'),null);assert.equal(host.querySelector('[role="dialog"]'),null,'learning completion stays inline');
 await act(async()=>root.unmount());opener.remove();
 console.log('PASS modal consumers: focus trap/return, exit lifecycle, duplicate close, reopen, unmount, inline learning');
}
main().then(()=>process.exit(0)).catch(e=>{console.error(e);process.exit(1);});
