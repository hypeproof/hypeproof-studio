// The CSS files are the only editable sources (designTokens.css, radiusScale.css, then focusGeometry.css); Chalk's Worker needs a TS text transport.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
export const source = new URL('../extensions/hypeproof-chat/webview-ui/src/designTokens.css', import.meta.url);
export const focusSource = new URL('../extensions/hypeproof-chat/webview-ui/src/focusGeometry.css', import.meta.url);
export const radiusSource = new URL('../extensions/hypeproof-chat/webview-ui/src/radiusScale.css', import.meta.url);
export const typographySource = new URL('../chalk/src/lib/typography.css', import.meta.url);
export const target = new URL('../chalk/src/lib/design-tokens.ts', import.meta.url);
// What Chalk serves: the token tiers, the radius scale (CGP-DS-R-011), then the shared focus geometry that reads the role tokens.
export function tokenCss() { return readFileSync(source, 'utf8') + readFileSync(radiusSource, 'utf8') + readFileSync(focusSource, 'utf8'); }
export function transport(css) {
  const typography = readFileSync(typographySource, 'utf8');
  const prose = readFileSync(new URL('../extensions/hypeproof-chat/webview-ui/src/koreanProse.css', import.meta.url), 'utf8');
  if (/<\/style/i.test(css)) throw new Error('Token CSS cannot close its style element');
  return '// Generated by scripts/sync-design-tokens.mjs. Edit designTokens.css, radiusScale.css, focusGeometry.css, koreanProse.css and chalk/src/lib/typography.css only.\n'
    + `export const DESIGN_TOKENS = ${JSON.stringify(css)};\n`
    + `export const CHALK_TYPOGRAPHY = ${JSON.stringify(typography)};\n`
    + `export const KOREAN_PROSE = ${JSON.stringify(prose)};\n`
    + 'export function withDesignTokens(html: string): string {\n'
    + '  const entry = /<head\\b[^>]*>/i.test(html) ? /<head\\b[^>]*>/i : /<html\\b[^>]*>/i;\n'
    + '  if (!entry.test(html)) throw new Error("Chalk page is missing its document root");\n'
    + '  return html.replace(entry, (head) => `${head}<style data-design-tokens>${DESIGN_TOKENS}</style><style data-korean-prose>${KOREAN_PROSE}</style><style data-chalk-typography>${CHALK_TYPOGRAPHY}</style>`);\n'
    + '}\n';
}
export function checkTransport() {
  if (readFileSync(target, 'utf8') !== transport(tokenCss())) throw new Error('Stale Chalk design tokens: run node scripts/sync-design-tokens.mjs');
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) checkTransport();
  else writeFileSync(target, transport(tokenCss()));
}
