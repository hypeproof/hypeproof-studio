#!/usr/bin/env python3
"""Generate RC isolation patch from pristine VS Code HEAD without editing it."""
import argparse
import difflib
from pathlib import Path
import subprocess

HERE = Path(__file__).resolve().parent
PATCH = HERE.parent / 'hps-rc-storage.patch'
SOURCE = 'src/main.ts'
HELPER = 'src/hpsRcStorage.ts'


def replace_once(source, before, after):
    if source.count(before) != 1:
        raise ValueError(f'Upstream anchor must occur exactly once: {before!r}')
    return source.replace(before, after)


def build(vscode):
    old = subprocess.run(['git', 'show', f'HEAD:{SOURCE}'], cwd=vscode,
                         check=True, capture_output=True, text=True).stdout
    new = replace_once(old, "import * as path from 'node:path';", "import * as path from 'node:path';\nimport { prepareRcStorage, validateRcUserDataPath, RC_STORAGE_NAME } from './hpsRcStorage.js';")
    new = replace_once(new, 'const args = parseCLIArgs();', "const args = parseCLIArgs();\nconst rcStorageProfile = prepareRcStorage(args, product, process.execPath, os.homedir(), process.platform, process.env);")
    new = replace_once(new, "const userDataPath = getUserDataPath(args, product.nameShort ?? 'code-oss-dev');", "const userDataPath = getUserDataPath(args, product.nameShort ?? 'code-oss-dev');\nvalidateRcUserDataPath(rcStorageProfile, userDataPath);\nif (rcStorageProfile) {\n\t// Electron 39 safeStorage derives its macOS service/account from this pre-ready name.\n\tapp.setName(RC_STORAGE_NAME);\n}")
    patch = 'Studio RC durable profile and fixed OS encryption namespace isolation.\nGenerated by rc-storage/build_patch.py; do not edit by hand.\n\n'
    for filename, before, after in [(SOURCE, old, new), (HELPER, '', (HERE / 'hpsRcStorage.ts').read_text())]:
        patch += ''.join(difflib.unified_diff(before.splitlines(True), after.splitlines(True), fromfile=('a/' + filename if before else '/dev/null'), tofile='b/' + filename))
    return patch


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('vscode', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    patch = build(args.vscode)
    if args.check:
        if PATCH.read_text() != patch:
            raise SystemExit('hps-rc-storage.patch is stale; regenerate it')
        print('hps-rc-storage.patch is current')
    else:
        PATCH.write_text(patch)
        print(f'Wrote {PATCH}')
