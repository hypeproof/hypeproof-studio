#!/usr/bin/env python3
"""Generate the task notice patch from pristine VS Code HEAD and notice-src/."""
import pathlib, shutil, subprocess, sys, tempfile
HERE = pathlib.Path(__file__).resolve().parent
PATCH = HERE / 'hps-task-notice.patch'
def git(*args, cwd):
    return subprocess.run(['git', *args], cwd=cwd, text=True, capture_output=True, check=True).stdout
def build(vscode):
    rel = 'src/vs/workbench/workbench.desktop.main.ts'
    anchor = "import './contrib/encryption/electron-browser/encryption.contribution.js';\n"
    with tempfile.TemporaryDirectory() as tmp:
        work = pathlib.Path(tmp); git('init', '-q', cwd=work)
        target = work / rel; target.parent.mkdir(parents=True)
        original = git('show', 'HEAD:' + rel, cwd=vscode)
        if original.count(anchor) != 1: raise RuntimeError('notice import anchor not unique')
        target.write_text(original); git('add', '-A', cwd=work)
        git('-c', 'user.name=hps', '-c', 'user.email=hps@invalid', 'commit', '-qm', 'base', cwd=work)
        target.write_text(original.replace(anchor, anchor + "import './contrib/hpsNotice/browser/hpsNotice.contribution.js';\n"))
        shutil.copytree(HERE / 'notice-src', work / 'src', dirs_exist_ok=True)
        git('add', '-A', cwd=work)
        return 'HypeProof Studio task notices. Generated by build_notice_patch.py.\n\n' + git('diff', '--cached', '--no-color', '--no-ext-diff', cwd=work)
if __name__ == '__main__':
    result = build(pathlib.Path(sys.argv[1]).resolve())
    if '--check' in sys.argv:
        if PATCH.read_text() != result: raise SystemExit('task notice patch is stale')
        print('task notice patch is current')
    else:
        PATCH.write_text(result); print(PATCH)
