#!/usr/bin/env python3
"""Generate the Korean NLS startup patch against pinned upstream fixtures."""
from pathlib import Path
import difflib
import json
HERE = Path(__file__).resolve().parent
settings_hook = "export function settingKeyToDisplayFormat(key: string, groupId: string = '', isLanguageTagSetting: boolean = false): { category: string; label: string } {"
settings_map = json.dumps(json.loads((HERE/'settings-labels.json').read_text()), ensure_ascii=False)
changes = {
 'src/vs/workbench/contrib/preferences/browser/settingsTreeModels.ts': ('settingsTreeModels.ts', settings_hook, settings_hook + '\n\tconst koreanLabels: Record<string, string> = ' + settings_map + ";\n\tif (Object.hasOwn(koreanLabels, key)) { return { category: '대화 설정', label: koreanLabels[key] }; }"),
 'src/vs/platform/menubar/electron-main/menubar.ts': ('menubar.ts', 'label: this.productService.nameShort, submenu: applicationMenu', "label: '하이프루프 스튜디오', submenu: applicationMenu"),
 'src/main.ts': ('main.ts', "const userLocale = getUserDefinedLocale(argvConfig);", "const userLocale = 'ko'; // Studio learner shell is Korean on every OS."),
 'src/vs/base/node/nls.ts': ('nls.ts', "\tmark('code/willGenerateNls');", """\tmark('code/willGenerateNls');

	// Studio ships a build-validated Korean bundle, independent of user language packs.
	if (!process.env['VSCODE_DEV']) {
		return {
			userLocale: 'ko', osLocale, resolvedLanguage: 'ko',
			defaultMessagesFile: join(nlsMetadataPath, 'nls.messages.ko.json'),
			locale: 'ko', availableLanguages: {}
		};
	}""")
}
patch = 'Studio Korean shell (CGP-SHELL-R-006). Generated by korean/build_patch.py.\n\n'
for path, (fixture, before, after) in changes.items():
 old = (HERE/'upstream'/fixture).read_text()
 assert old.count(before)==1
 new = old.replace(before,after)
 if fixture == 'menubar.ts':
  new = new.replace("'lastKnownMenubarData'", "'lastKnownMenubarData.ko.v1'")
 if fixture == 'main.ts':
  new = new.replace("if (process.platform === 'win32' || process.platform === 'linux') {\n\tconst electronLocale", "if (true) { // Include macOS native role labels.\n\tconst electronLocale")
  # Avoid TS narrowing errors now that userLocale is a literal.
  new = new.replace("(!userLocale || userLocale === 'qps-ploc') ? 'en' : userLocale", "userLocale")
 patch += ''.join(difflib.unified_diff(old.splitlines(True),new.splitlines(True),fromfile='a/'+path,tofile='b/'+path))
(HERE.parent/'hps-korean-shell.patch').write_text(patch)
