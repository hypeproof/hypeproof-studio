#!/usr/bin/env python3
"""Generate the secure-storage patch from pristine VS Code HEAD, without editing it."""
import argparse
import difflib
from pathlib import Path
import subprocess

HERE = Path(__file__).resolve().parent
PATCH = HERE.parent / 'hps-secure-storage.patch'
SOURCE = 'src/vs/platform/secrets/common/secrets.ts'
HEADER = '''Studio secure storage: lazy OS encryption access, recoverable failures, no implicit fallback.
Generated by secure-storage/build_patch.py from pristine VS Code HEAD. Do not edit by hand.
Staged by scripts/stage-core-patches.sh as 99-hps-secure-storage.patch.

'''


def replace_once(source, before, after):
    if source.count(before) != 1:
        raise ValueError(f'Upstream anchor must occur exactly once: {before!r}')
    return source.replace(before, after)


def transform(source):
    source = replace_once(source,
        "\tprivate readonly _onDidChangeValueDisposable = this._register(new DisposableStore());",
        "\tprivate _inMemoryStorageService: IStorageService | undefined;\n\n"
        "\tprivate readonly _onDidChangeValueDisposable = this._register(new DisposableStore());")
    source = replace_once(source, '\t\t\tif (!encrypted) {', '\t\t\tif (encrypted === undefined) {')
    source = replace_once(source,
        "\t\t\t\tthis._logService.trace('[secrets] decrypting gotten secret for key:', fullKey);",
        "\t\t\t\tawait this.ensureEncryptionAvailable();\n"
        "\t\t\t\tthis._logService.trace('[secrets] decrypting gotten secret for key:', fullKey);")
    source = replace_once(source,
        '\t\t\t\tthis.delete(key);\n\t\t\t\treturn undefined;',
        '\t\t\t\t// A locked keychain or denied access must never erase the saved ciphertext.\n'
        '\t\t\t\tthrow e;')
    source = replace_once(source,
        "\t\t\t\t// If the storage service is in-memory, we don't need to encrypt",
        "\t\t\t\tawait this.ensureEncryptionAvailable();\n"
        "\t\t\t\t// If the storage service is in-memory, we don't need to encrypt")
    start = source.index('\tprivate async initialize(): Promise<IStorageService> {')
    end = source.index('\n\t\tthis._onDidChangeValueDisposable.clear();', start)
    source = source[:start] + '''\tprivate async ensureEncryptionAvailable(): Promise<void> {
		// Do not cache failures: the next operation can retry after access is restored.
		if (!this._useInMemoryStorage && !await this._encryptionService.isEncryptionAvailable()) {
			throw new Error('Secret storage encryption is unavailable. Unlock or allow access to the OS keychain, then retry.');
		}
	}

	private async initialize(): Promise<IStorageService> {
		// Listing keys and checking for a missing secret only need storage metadata.
		// Access the OS keychain only when reading or writing an actual secret.
		const storageService = this._useInMemoryStorage
			? this._inMemoryStorageService ??= this._register(new InMemoryStorageService())
			: this._storageService;
		this._type = this._useInMemoryStorage ? 'in-memory' : 'persisted';
''' + source[end:]
    return source


def build(vscode):
    original = subprocess.run(['git', 'show', f'HEAD:{SOURCE}'], cwd=vscode,
                              check=True, capture_output=True, text=True).stdout
    return HEADER + ''.join(difflib.unified_diff(original.splitlines(True),
        transform(original).splitlines(True), fromfile='a/' + SOURCE, tofile='b/' + SOURCE))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('vscode', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    patch = build(args.vscode)
    if args.check:
        if PATCH.read_text() != patch:
            raise SystemExit('hps-secure-storage.patch is stale; regenerate it')
        print('hps-secure-storage.patch is current')
    else:
        PATCH.write_text(patch)
        print(f'Wrote {PATCH}')
