#!/usr/bin/env python3
"""Regenerate scripts/patches/core/hps-quit-guard.patch from the canonical sources.

The patch adds the files under scripts/patches/core/src/ verbatim and makes two hook edits
(dialogs.ts massage passthrough, workbench.desktop.main.ts import). The base is the pristine
upstream commit of a VS Code checkout (`git show HEAD:<path>`), so an already-patched tree
works too.

    python3 scripts/patches/core/build_quit_guard_patch.py <vscode-tree>          # write
    python3 scripts/patches/core/build_quit_guard_patch.py <vscode-tree> --check  # compare

The VS Code tree is vscodium-base/vscode after get_repo.sh (main checkout or CI).
"""
import pathlib
import shutil
import subprocess
import sys
import tempfile

HERE = pathlib.Path(__file__).resolve().parent
PATCH = HERE / "hps-quit-guard.patch"
SRC = HERE / "src"

HEADER = """\
HypeProof Studio quit guard (REQ-STUDIO-QUIT-GUARD; CGP-SHELL-R-004 / CGP-SHELL-D-003).
Generated by scripts/patches/core/build_quit_guard_patch.py. Do not edit by hand: change
scripts/patches/core/src/ or the hooks in the generator, then regenerate.
Staged into vscodium-base/patches/user/ by scripts/stage-core-patches.sh.

"""

# Replace the local stop joiner with a Last joiner, matching the remote-host path.
# Default joiners (including the staged updater) still need the extension host alive.
REPLACEMENTS = [(
    "src/vs/workbench/services/extensions/common/abstractExtensionService.ts",
    "event.join(this._doStopExtensionHosts(), {\n\t\t\t\t\tid: 'join.stopExtensionHosts',\n\t\t\t\t\tlabel: nls.localize('stopExtensionHosts', \"Stopping Extension Hosts\"),",
    "event.join(() => this._doStopExtensionHosts(), {\n\t\t\t\t\tid: 'join.stopExtensionHosts',\n\t\t\t\t\tlabel: nls.localize('stopExtensionHosts', \"Stopping Extension Hosts\"),\n\t\t\t\t\torder: WillShutdownJoinerOrder.Last,",
)]

HOOKS = [
    (
        "src/vs/platform/dialogs/common/dialogs.ts",
        "import { deepClone } from '../../../base/common/objects.js';\n",
        "import { hpsIsSafeDefaultDialog, hpsMassageSafeDefaultDialog } from './hpsSafeDefaultDialog.js';\n",
    ),
    (
        "src/vs/platform/dialogs/common/dialogs.ts",
        "export function massageMessageBoxOptions(options: MessageBoxOptions, productService: IProductService): IMassagedMessageBoxOptions {\n",
        "\tif (hpsIsSafeDefaultDialog(options)) {\n"
        "\t\treturn hpsMassageSafeDefaultDialog(options, productService.nameLong, button => mnemonicButtonLabel(button).withMnemonic);\n"
        "\t}\n\n",
    ),
    (
        "src/vs/workbench/workbench.desktop.main.ts",
        "import './contrib/keybindingsExport/electron-browser/keybindingsExport.contribution.js';\n",
        "\n// HypeProof Studio: confirm before a quit or window close stops a coach turn\n"
        "import './contrib/hpsQuitGuard/electron-browser/hpsQuitGuard.contribution.js';\n",
    ),
]


def git(*args, cwd):
    return subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True, text=True).stdout


def build(vscode: pathlib.Path) -> str:
    with tempfile.TemporaryDirectory() as tmp:
        work = pathlib.Path(tmp)
        git("init", "-q", cwd=work)
        for rel in sorted({h[0] for h in HOOKS + REPLACEMENTS}):
            target = work / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(git("show", f"HEAD:{rel}", cwd=vscode))
        git("add", "-A", cwd=work)
        git("-c", "user.name=hps", "-c", "user.email=hps@invalid", "commit", "-qm", "base", cwd=work)
        for rel, anchor, insert in HOOKS:
            target = work / rel
            text = target.read_text()
            if text.count(anchor) != 1:
                sys.exit(f"anchor not found exactly once in {rel}: {anchor.strip()}")
            target.write_text(text.replace(anchor, anchor + insert))
        for rel, before, after in REPLACEMENTS:
            target = work / rel
            text = target.read_text()
            if text.count(before) != 1:
                sys.exit(f"replacement anchor not unique: {rel}")
            target.write_text(text.replace(before, after))
        shutil.copytree(SRC, work / "src", dirs_exist_ok=True)
        git("add", "-A", cwd=work)
        return HEADER + git("diff", "--cached", "--no-color", "--no-ext-diff", "--src-prefix=a/", "--dst-prefix=b/", cwd=work)


def main() -> None:
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    patch = build(pathlib.Path(sys.argv[1]).resolve())
    if "--check" in sys.argv[2:]:
        if PATCH.read_text() != patch:
            sys.exit("hps-quit-guard.patch is stale: regenerate it")
        print("hps-quit-guard.patch is current")
        return
    PATCH.write_text(patch)
    print(f"wrote {PATCH}")


if __name__ == "__main__":
    main()
