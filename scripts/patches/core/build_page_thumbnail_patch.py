#!/usr/bin/env python3
import pathlib,subprocess,tempfile,sys
HERE=pathlib.Path(__file__).resolve().parent
REL='src/vs/workbench/workbench.desktop.main.ts'
def run(*args,cwd):return subprocess.check_output(args,cwd=cwd,text=True)
def build(upstream):
 original=run('git','show','HEAD:'+REL,cwd=upstream)
 anchor="import './services/browserView/electron-browser/playwrightWorkbenchService.js';"
 assert original.count(anchor)==1
 modified=original.replace(anchor,anchor+"\nimport './contrib/hpsPageThumbnail/electron-browser/hpsPageThumbnail.contribution.js';")
 with tempfile.TemporaryDirectory() as tmp:
  root=pathlib.Path(tmp);run('git','init','-q',cwd=root);p=root/REL;p.parent.mkdir(parents=True);p.write_text(original);run('git','add','.',cwd=root);run('git','-c','user.name=patch','-c','user.email=patch@invalid','commit','-qm','base',cwd=root);p.write_text(modified)
  for f in (HERE/'page-thumbnail-src').rglob('*'):
   if f.is_file():
    dest=root/'src'/f.relative_to(HERE/'page-thumbnail-src');dest.parent.mkdir(parents=True,exist_ok=True);dest.write_bytes(f.read_bytes())
  run('git','add','-A',cwd=root);return 'Studio isolated page thumbnails (CGP-ART-D-010). Generated by build_page_thumbnail_patch.py.\n\n'+run('git','diff','--cached',cwd=root)
if __name__=='__main__':
 result=build(pathlib.Path(sys.argv[1]));target=HERE/'hps-page-thumbnail.patch'
 if '--check' in sys.argv:assert target.read_text()==result,'stale thumbnail patch'
 else:target.write_text(result)
 print('page thumbnail patch current')
