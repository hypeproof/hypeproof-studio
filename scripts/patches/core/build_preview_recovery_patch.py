REL='src/vs/workbench/contrib/browserView/electron-browser/browserEditor.ts'
METHOD='''
	override dispose(): void {
		this.clearHpsRecovery();
		super.dispose();
	}
	private _hpsRecoveryEpoch = 0;
	private _hpsRecoveryShown = false;
	private _hpsRecoveryDispose: (() => void) | undefined;

	private clearHpsRecovery(): void {
		this._hpsRecoveryEpoch++;
		this._hpsRecoveryDispose?.();
		this._hpsRecoveryDispose = undefined;
		this._hpsRecoveryShown = false;
	}

	private async refreshHpsRecovery(): Promise<void> {
		const model = this._model, epoch = this._hpsRecoveryEpoch;
		if (!model || model.loading || !model.url) { return; }
		const url = model.url;
		const current = () => this._model === model && model.url === url && this._hpsRecoveryEpoch === epoch;
		const commands = this.instantiationService.invokeFunction(accessor => accessor.get(ICommandService));
		try {
			const response = await commands.executeCommand('_hps.previewRecovery.resolve', url);
			if (!current()) { return; }
			const view = parseHpsPreviewRecovery(response, url);
			if (!view) { return; }
			this._certActionButton.clear();
			this._hpsRecoveryShown = true;
			this.updateVisibility();
			this._hpsRecoveryDispose = renderHpsPreviewRecovery(this._errorContainer, view, async (id, target, action) => {
				if (!current()) { return false; }
				try {
					return await commands.executeCommand<boolean>('_hps.previewRecovery.act', id, target, action) === true;
				} finally {
					// Every attempt consumes its token, including refusal/failure. Obtain a fresh measured request.
					if (current()) { this.updateErrorDisplay(); }
				}
			}, this._editorVisible);
		} catch { /* Extension unavailable: preserve the normal browser error. */ }
	}
'''
